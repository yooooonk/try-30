def build():
    out = []
    for i, (name, cat, label, g, fiber, protein, fsrc, psrc) in enumerate(FOODS, 1):
        if isinstance(fiber, tuple):
            fiber = round(fiber[1] / g * 100, 1)
        out.append({
            "id": f"f{i:03d}",
            "name": name,
            "category": cat,
            "serving": {"label": label, "g": g},
            "per100": {"fiber": fiber, "protein": protein},
            "src": {"fiber": fsrc, "protein": psrc},
        })
    return out


if __name__ == "__main__":
    foods = build()
    path = Path(__file__).with_name("foods.json")
    path.write_text(json.dumps(foods, ensure_ascii=False, indent=2) + "\n")
    print(f"{len(foods)} foods → {path.name}")
